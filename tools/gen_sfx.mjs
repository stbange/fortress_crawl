#!/usr/bin/env node
// Generates the game's sound effects with the ElevenLabs sound effects API.
//
//   npm install                          (once: installs @elevenlabs/elevenlabs-js)
//   npm run sfx                          (generates every missing file in assets/sfx)
//   npm run sfx -- --only=brute_alert,loop_mines --force   (regenerate some)
//   npm run sfx -- --header              (only rewrite src/game/sfx_ids.h)
//
// The API key comes from the ELEVENLABS_API_KEY environment variable (or .env.local, which
// `elevenlabs onboard` writes and git ignores). Files that exist are skipped, so a run that
// stopped can simply be started again. The list of sounds is tools/sfx_list.mjs.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ElevenLabsClient } from "@elevenlabs/elevenlabs-js";
import { SOUNDS, STYLE } from "./sfx_list.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "assets", "sfx");
const HEADER = path.join(ROOT, "src", "game", "sfx_ids.h");
const FORMAT = "wav_22050"; /* 22 kHz mono 16-bit: plenty for a retro game, half the size of 44.1 */
const MODELS = ["eleven_text_to_sound_v3", "eleven_text_to_sound_v2"]; /* the newest first */

const args = process.argv.slice(2);
const flag = (name) => args.some((a) => a === `--${name}`);
const opt = (name) => args.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);

function loadEnvLocal() {
  if (process.env.ELEVENLABS_API_KEY) return;
  const f = path.join(ROOT, ".env.local");
  if (!fs.existsSync(f)) return;
  for (const line of fs.readFileSync(f, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*"?([^"]*)"?\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
  }
}

function files(s) {
  const n = s.v || 1;
  return n === 1 ? [`${s.id}.wav`] : Array.from({ length: n }, (_, i) => `${s.id}_${i + 1}.wav`);
}

function writeHeader() {
  const lines = [];
  lines.push("/* Generated by tools/gen_sfx.mjs from tools/sfx_list.mjs - do not edit. */");
  lines.push("#ifndef FC_SFX_IDS_H");
  lines.push("#define FC_SFX_IDS_H");
  lines.push("");
  lines.push("enum {");
  for (const s of SOUNDS) lines.push(`    SFX_${s.id.toUpperCase()},`);
  lines.push("    SFX_COUNT");
  lines.push("};");
  lines.push("");
  lines.push("typedef struct SfxDef { const char *name; unsigned char variants; unsigned char loop; } SfxDef;");
  lines.push("");
  lines.push("static const SfxDef SFX_DEFS[SFX_COUNT] = {");
  for (const s of SOUNDS) lines.push(`    { "${s.id}", ${s.v || 1}, ${s.loop ? 1 : 0} },`);
  lines.push("};");
  lines.push("");
  lines.push("#endif");
  fs.writeFileSync(HEADER, lines.join("\n") + "\n");
  console.log(`wrote ${path.relative(ROOT, HEADER)} (${SOUNDS.length} sounds)`);
}

const verbose = flag("verbose");

/* Mono 16-bit, and one-shots without the silence before and after them (a hit must sound at once). */
function tidy(wav, loop) {
  let pos = 12, fmt = null, data = null;
  while (pos + 8 <= wav.length) {
    const id = wav.toString("ascii", pos, pos + 4), size = wav.readUInt32LE(pos + 4);
    if (id === "fmt ") fmt = { ch: wav.readUInt16LE(pos + 10), rate: wav.readUInt32LE(pos + 12), bits: wav.readUInt16LE(pos + 22) };
    if (id === "data") data = wav.subarray(pos + 8, pos + 8 + Math.min(size, wav.length - pos - 8));
    pos += 8 + size + (size & 1);
  }
  if (!fmt || !data || fmt.bits !== 16) throw new Error("unexpected WAV layout");
  const n = Math.floor(data.length / (2 * fmt.ch));
  let mono = new Int16Array(n);
  for (let i = 0; i < n; i++) {
    let sum = 0;
    for (let c = 0; c < fmt.ch; c++) sum += data.readInt16LE((i * fmt.ch + c) * 2);
    mono[i] = Math.round(sum / fmt.ch);
  }
  if (!loop) {
    const thr = 32768 * 0.004; /* about -48 dB */
    let a = 0, b = n - 1;
    while (a < n && Math.abs(mono[a]) < thr) a++;
    while (b > a && Math.abs(mono[b]) < thr) b--;
    a = Math.max(0, a - Math.round(fmt.rate * 0.004));
    b = Math.min(n - 1, b + Math.round(fmt.rate * 0.03));
    mono = mono.slice(a, b + 1);
    const fade = Math.min(mono.length, Math.round(fmt.rate * 0.02)); /* no click at the end */
    for (let i = 0; i < fade; i++) mono[mono.length - 1 - i] = Math.round(mono[mono.length - 1 - i] * (i / fade));
  }
  normalize(mono, loop);
  return wavFile(mono, fmt.rate);
}

/* Even levels: one-shots peak at -2 dB, loops sit at about -24 dB RMS (the game sets the mix). */
function normalize(mono, loop) {
  let peak = 1, sum = 0;
  for (const x of mono) { peak = Math.max(peak, Math.abs(x)); sum += x * x; }
  const rms = Math.sqrt(sum / Math.max(1, mono.length)) || 1;
  let gain = loop ? (32768 * 0.063) / rms : (32768 * 0.79) / peak;
  gain = Math.min(gain, 8, (32768 * 0.89) / peak); /* at most +18 dB, never above -1 dB peak */
  for (let i = 0; i < mono.length; i++) mono[i] = Math.max(-32768, Math.min(32767, Math.round(mono[i] * gain)));
}

function wavFile(mono, rate) {
  const fmt = { rate };
  const out = Buffer.alloc(44 + mono.length * 2);
  out.write("RIFF", 0); out.writeUInt32LE(36 + mono.length * 2, 4); out.write("WAVE", 8);
  out.write("fmt ", 12); out.writeUInt32LE(16, 16); out.writeUInt16LE(1, 20); out.writeUInt16LE(1, 22);
  out.writeUInt32LE(fmt.rate, 24); out.writeUInt32LE(fmt.rate * 2, 28); out.writeUInt16LE(2, 32); out.writeUInt16LE(16, 34);
  out.write("data", 36); out.writeUInt32LE(mono.length * 2, 40);
  for (let i = 0; i < mono.length; i++) out.writeInt16LE(mono[i], 44 + i * 2);
  return out;
}

async function generate(client, s, file) {
  const text = `${s.text}. ${STYLE}`;
  let lastErr;
  for (const modelId of MODELS) {
    try {
      const stream = await client.textToSoundEffects.convert({
        text,
        durationSeconds: Math.min(30, Math.max(0.5, s.dur)), /* the API takes 0.5 .. 30 s */
        loop: !!s.loop,
        promptInfluence: s.loop ? 0.45 : 0.6,
        outputFormat: FORMAT,
        modelId,
      });
      const chunks = [];
      for await (const c of stream) chunks.push(c);
      const raw = Buffer.concat(chunks);
      if (raw.length < 64 || raw.toString("ascii", 0, 4) !== "RIFF") throw new Error(`not a WAV file (${raw.length} bytes)`);
      const buf = tidy(raw, !!s.loop);
      fs.writeFileSync(path.join(OUT, file), buf);
      if (verbose) console.log(`  ${file}: model ${modelId}, ${(buf.length / 1e3).toFixed(0)} kB`);
      return buf.length;
    } catch (e) {
      lastErr = e;
      if (e?.statusCode === 401 || e?.statusCode === 402 || e?.statusCode === 429) break; /* key, credits, quota */
    }
  }
  throw lastErr;
}

async function main() {
  const ids = new Set(SOUNDS.map((s) => s.id));
  if (ids.size !== SOUNDS.length) throw new Error("duplicate ids in tools/sfx_list.mjs");
  writeHeader();
  if (flag("header")) return;
  if (flag("normalize")) {
    /* level the files already there, without calling the API */
    for (const s of SOUNDS)
      for (const f of files(s)) {
        const p = path.join(OUT, f);
        if (!fs.existsSync(p)) continue;
        const wav = fs.readFileSync(p);
        const mono = new Int16Array(wav.buffer.slice(wav.byteOffset + 44, wav.byteOffset + wav.length));
        normalize(mono, !!s.loop);
        fs.writeFileSync(p, wavFile(mono, wav.readUInt32LE(24)));
      }
    console.log("normalized");
    return;
  }

  loadEnvLocal();
  if (!process.env.ELEVENLABS_API_KEY) {
    console.error("ELEVENLABS_API_KEY is not set (run `npx -y @elevenlabs/cli@latest onboard init` first).");
    process.exit(1);
  }
  fs.mkdirSync(OUT, { recursive: true });
  const client = new ElevenLabsClient();
  const only = opt("only")?.split(",");
  const force = flag("force");
  const jobs = [];
  for (const s of SOUNDS) {
    if (only && !only.includes(s.id)) continue;
    for (const f of files(s)) if (force || !fs.existsSync(path.join(OUT, f))) jobs.push([s, f]);
  }
  console.log(`${jobs.length} files to generate`);
  let done = 0, failed = 0, bytes = 0;
  const workers = Number(opt("jobs") || 3);
  let next = 0;
  async function worker() {
    while (next < jobs.length) {
      const [s, f] = jobs[next++];
      try {
        const n = await generate(client, s, f);
        bytes += n;
        done++;
        console.log(`[${done + failed}/${jobs.length}] ${f}`);
      } catch (e) {
        failed++;
        console.error(`[${done + failed}/${jobs.length}] ${f} FAILED: ${e?.statusCode ?? ""} ${JSON.stringify(e?.body ?? e?.message ?? e)}`);
        if (e?.statusCode === 401 || e?.statusCode === 402) { next = jobs.length; }
      }
    }
  }
  await Promise.all(Array.from({ length: workers }, worker));
  console.log(`done: ${done} generated (${(bytes / 1e6).toFixed(1)} MB), ${failed} failed`);
  if (failed) process.exit(1);
}

main().catch((e) => { console.error(e); process.exit(1); });
