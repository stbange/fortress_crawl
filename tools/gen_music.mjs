#!/usr/bin/env node
// Generates the game's music with the ElevenLabs music API.
//
//   npm run music                              (makes every missing file in assets/music)
//   npm run music -- --only=battle --force     (makes one again)
//   npm run music -- --header                  (only rewrites src/game/music_ids.h)
//
// The API key comes from ELEVENLABS_API_KEY (or .env.local, written by `elevenlabs onboard`).
// The pieces and their descriptions are in tools/music_list.mjs. The audio is asked for as raw
// 22 kHz PCM and stored as mono 16-bit WAV, levelled, with short fades at both ends.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ElevenLabsClient } from "@elevenlabs/elevenlabs-js";
import { MUSIC } from "./music_list.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "assets", "music");
const HEADER = path.join(ROOT, "src", "game", "music_ids.h");
const RATE = 22050;

const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);
const opt = (name) => args.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);

function loadEnvLocal() {
  if (process.env.ELEVENLABS_API_KEY) return;
  const f = path.join(ROOT, ".env.local");
  if (!fs.existsSync(f)) return;
  for (const line of fs.readFileSync(f, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*"?([^"]*)"?\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
  }
}

function writeHeader() {
  const L = ["/* Generated by tools/gen_music.mjs from tools/music_list.mjs - do not edit. */", "#ifndef FC_MUSIC_IDS_H", "#define FC_MUSIC_IDS_H", "", "enum {"];
  for (const m of MUSIC) L.push(`    MUS_${m.id.toUpperCase()}, /* ${m.when} */`);
  L.push("    MUS_COUNT", "};", "", "static const char *const MUSIC_NAMES[MUS_COUNT] = {");
  for (const m of MUSIC) L.push(`    "${m.id}",`);
  L.push("};", "", "#endif");
  fs.writeFileSync(HEADER, L.join("\n") + "\n");
  console.log(`wrote ${path.relative(ROOT, HEADER)} (${MUSIC.length} pieces)`);
}

function wav(mono) {
  const out = Buffer.alloc(44 + mono.length * 2);
  out.write("RIFF", 0); out.writeUInt32LE(36 + mono.length * 2, 4); out.write("WAVE", 8);
  out.write("fmt ", 12); out.writeUInt32LE(16, 16); out.writeUInt16LE(1, 20); out.writeUInt16LE(1, 22);
  out.writeUInt32LE(RATE, 24); out.writeUInt32LE(RATE * 2, 28); out.writeUInt16LE(2, 32); out.writeUInt16LE(16, 34);
  out.write("data", 36); out.writeUInt32LE(mono.length * 2, 40);
  for (let i = 0; i < mono.length; i++) out.writeInt16LE(mono[i], 44 + i * 2);
  return out;
}

/* Raw 16-bit PCM (mono or stereo) to levelled mono with fades. */
function tidy(pcm, seconds) {
  const frames = Math.floor(pcm.length / 2);
  /* the API sends mono or interleaved stereo; the length tells which */
  const ch = Math.abs(frames / (RATE * seconds) - 2) < Math.abs(frames / (RATE * seconds) - 1) ? 2 : 1;
  const n = Math.floor(frames / ch);
  const mono = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    let s = 0;
    for (let c = 0; c < ch; c++) s += pcm.readInt16LE((i * ch + c) * 2);
    mono[i] = s / ch;
  }
  return { mono: level(trimTail(mono)), ch };
}

/* Drop the silence some pieces end with (the fade-out goes on the music, not on nothing). */
function trimTail(mono) {
  const thr = 32768 * 0.003;
  let end = mono.length;
  while (end > RATE && Math.abs(mono[end - 1]) < thr) end--;
  return mono.subarray(0, Math.min(mono.length, end + Math.round(RATE * 0.5)));
}

function level(mono) {
  const n = mono.length;
  let peak = 1;
  for (const x of mono) peak = Math.max(peak, Math.abs(x));
  const gain = (32768 * 0.89) / peak; /* peak at -1 dB; the game sets the music volume */
  const fadeIn = Math.round(RATE * 0.5), fadeOut = Math.round(RATE * 3.0);
  const out = new Int16Array(n);
  for (let i = 0; i < n; i++) {
    let g = gain;
    if (i < fadeIn) g *= i / fadeIn;
    if (i > n - fadeOut) g *= (n - i) / fadeOut;
    out[i] = Math.max(-32768, Math.min(32767, Math.round(mono[i] * g)));
  }
  return out;
}

async function main() {
  writeHeader();
  if (flag("header")) return;
  if (flag("retidy")) {
    /* trim and level the files already there, without calling the API */
    for (const m of MUSIC) {
      const p = path.join(OUT, `${m.id}.wav`);
      if (!fs.existsSync(p)) continue;
      const w = fs.readFileSync(p);
      const pcm = new Int16Array(w.buffer.slice(w.byteOffset + 44, w.byteOffset + w.length));
      const out = level(trimTail(Float32Array.from(pcm)));
      fs.writeFileSync(p, wav(out));
      console.log(`${m.id}.wav: ${(out.length / RATE).toFixed(1)} s`);
    }
    return;
  }
  loadEnvLocal();
  if (!process.env.ELEVENLABS_API_KEY) {
    console.error("ELEVENLABS_API_KEY is not set (run `npx -y @elevenlabs/cli@latest onboard init` first).");
    process.exit(1);
  }
  fs.mkdirSync(OUT, { recursive: true });
  const client = new ElevenLabsClient({ timeoutInSeconds: 600 });
  const only = opt("only")?.split(",");
  const jobs = MUSIC.filter((m) => (!only || only.includes(m.id)) && (flag("force") || !fs.existsSync(path.join(OUT, `${m.id}.wav`))));
  console.log(`${jobs.length} pieces to make`);
  let failed = 0;
  /* the API allows two requests at a time on most plans */
  let next = 0;
  const one = async (m) => {
      try {
        const stream = await client.music.compose({
          prompt: m.text,
          musicLengthMs: m.sec * 1000,
          forceInstrumental: true,
          outputFormat: "pcm_22050",
        });
        const chunks = [];
        for await (const c of stream) chunks.push(c);
        const { mono, ch } = tidy(Buffer.concat(chunks), m.sec);
        fs.writeFileSync(path.join(OUT, `${m.id}.wav`), wav(mono));
        console.log(`${m.id}.wav: ${(mono.length / RATE).toFixed(1)} s (${ch === 2 ? "stereo" : "mono"} from the API), ${((44 + mono.length * 2) / 1e6).toFixed(1)} MB`);
      } catch (e) {
        failed++;
        console.error(`${m.id} FAILED: ${e?.statusCode ?? ""} ${JSON.stringify(e?.body ?? e?.message ?? String(e))}`);
      }
  };
  const worker = async () => { while (next < jobs.length) await one(jobs[next++]); };
  await Promise.all([worker(), worker()]);
  if (failed) process.exit(1);
}

main().catch((e) => { console.error(e); process.exit(1); });
