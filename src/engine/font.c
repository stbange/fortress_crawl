#define CELL_W 6
#define CELL_H 8
#define MAX_CHARS 4096

static GLuint g_tex, g_prog, g_vao, g_vbo;
static GLint g_u_tex;
static float *g_verts;
static int g_nverts;
static int g_tw, g_th;

static const char *VS =
    "#version 330 core\n"
    "layout(location=0) in vec2 a_pos;\n"
    "layout(location=1) in vec2 a_uv;\n"
    "layout(location=2) in vec3 a_col;\n"
    "out vec2 v_uv; out vec3 v_col;\n"
    "void main() { v_uv = a_uv; v_col = a_col; gl_Position = vec4(a_pos, 0.0, 1.0); }\n";
static const char *FS =
    "#version 330 core\n"
    "in vec2 v_uv; in vec3 v_col;\n"
    "uniform sampler2D u_tex;\n"
    "out vec4 frag;\n"
    "void main() { if (texture(u_tex, v_uv).r < 0.5) discard; frag = vec4(v_col, 1.0); }\n";

void font_init(void) {
    int w = 64 * CELL_W, h = CELL_H;
    unsigned char *pix = calloc((size_t)w * h, 1);
    for (int c = 0; c < 64; c++)
        for (int y = 0; y < 7; y++)
            for (int x = 0; x < 5; x++)
                if (GLYPHS[c][y] & (0x10 >> x)) pix[y * w + c * CELL_W + x] = 255;
    glGenTextures(1, &g_tex);
    glBindTexture(GL_TEXTURE_2D, g_tex);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, w, h, 0, GL_RED, GL_UNSIGNED_BYTE, pix);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 4);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    free(pix);
    g_prog = shader_program("font", VS, FS);
    g_u_tex = glGetUniformLocation(g_prog, "u_tex");
    glGenVertexArrays(1, &g_vao);
    glGenBuffers(1, &g_vbo);
    glBindVertexArray(g_vao);
    glBindBuffer(GL_ARRAY_BUFFER, g_vbo);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 7 * sizeof(float), (void *)0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 7 * sizeof(float), (void *)(2 * sizeof(float)));
    glEnableVertexAttribArray(2);
    glVertexAttribPointer(2, 3, GL_FLOAT, GL_FALSE, 7 * sizeof(float), (void *)(4 * sizeof(float)));
    glBindVertexArray(0);
    g_verts = malloc(sizeof(float) * 7 * 6 * MAX_CHARS);
}

void font_begin(int target_w, int target_h) {
    g_tw = target_w;
    g_th = target_h;
    g_nverts = 0;
}

static void push(float px, float py, float u, float v, float r, float g, float b) {
    float *q = g_verts + (size_t)g_nverts * 7;
    q[0] = px / g_tw * 2.0f - 1.0f;
    q[1] = 1.0f - py / g_th * 2.0f;
    q[2] = u; q[3] = v; q[4] = r; q[5] = g; q[6] = b;
    g_nverts++;
}

static void glyph(int x, int y, int c, float r, float g, float b) {
    if (g_nverts + 6 > 6 * MAX_CHARS) return;
    float u0 = (float)(c * CELL_W) / (64 * CELL_W), u1 = (float)(c * CELL_W + CELL_W) / (64 * CELL_W);
    float x0 = (float)x, y0 = (float)y, x1 = (float)(x + CELL_W), y1 = (float)(y + CELL_H);
    push(x0, y0, u0, 0, r, g, b); push(x1, y0, u1, 0, r, g, b); push(x1, y1, u1, 1, r, g, b);
    push(x0, y0, u0, 0, r, g, b); push(x1, y1, u1, 1, r, g, b); push(x0, y1, u0, 1, r, g, b);
}

void font_text(int x, int y, const char *s, float r, float g, float b) {
    for (int pass = 0; pass < 2; pass++) {
        int cx = x + (pass == 0), cy = y + (pass == 0);
        for (const char *p = s; *p; p++) {
            int ch = (unsigned char)*p;
            if (ch == '\n') { cx = x + (pass == 0); cy += FONT_LINE; continue; }
            if (ch >= 'a' && ch <= 'z') ch -= 32;
            if (ch < 32 || ch > 95) ch = '?';
            if (pass == 0) glyph(cx, cy, ch - 32, 0, 0, 0);
            else glyph(cx, cy, ch - 32, r, g, b);
            cx += CELL_W;
        }
    }
}

int font_text_width(const char *s) { return (int)strlen(s) * CELL_W; }

void font_end(void) {
    if (!g_nverts) return;
    glUseProgram(g_prog);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, g_tex);
    glUniform1i(g_u_tex, 0);
    glBindVertexArray(g_vao);
    glBindBuffer(GL_ARRAY_BUFFER, g_vbo);
    glBufferData(GL_ARRAY_BUFFER, (GLsizeiptr)(sizeof(float) * 7 * (size_t)g_nverts), g_verts, GL_STREAM_DRAW);
    glDrawArrays(GL_TRIANGLES, 0, g_nverts);
    glBindVertexArray(0);
    g_nverts = 0;
}
